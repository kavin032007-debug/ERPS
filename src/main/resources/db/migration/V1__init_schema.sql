-- Flyway Migration V1: Schema Initialization for Examination Result Processing System (ERPS)

CREATE TABLE institution_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    address TEXT,
    logo_ref VARCHAR(255),
    university_name VARCHAR(255) NOT NULL
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(255) NOT NULL,
    role VARCHAR(50) NOT NULL,
    mfa_secret VARCHAR(255),
    mfa_enabled BOOLEAN DEFAULT FALSE,
    enabled BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE departments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL
);

CREATE TABLE programmes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    department_id BIGINT REFERENCES departments(id) ON DELETE SET NULL
);

CREATE TABLE regulations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    effective_from_batch INTEGER NOT NULL
);

CREATE TABLE semesters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    semester_number INTEGER NOT NULL,
    academic_year VARCHAR(50) NOT NULL,
    UNIQUE(semester_number, academic_year)
);

CREATE TABLE students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    register_no VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    department_id BIGINT REFERENCES departments(id) ON DELETE RESTRICT,
    programme_id BIGINT REFERENCES programmes(id) ON DELETE RESTRICT,
    regulation_id BIGINT REFERENCES regulations(id) ON DELETE RESTRICT,
    batch_year INTEGER NOT NULL,
    current_semester INTEGER NOT NULL,
    email VARCHAR(255) NOT NULL
);

CREATE TABLE faculty (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    department_id BIGINT REFERENCES departments(id) ON DELETE RESTRICT,
    designation VARCHAR(100),
    email VARCHAR(255) NOT NULL
);

CREATE TABLE courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    title VARCHAR(255) NOT NULL,
    credits NUMERIC(4,1) NOT NULL,
    semester INTEGER NOT NULL,
    type VARCHAR(50) NOT NULL DEFAULT 'THEORY',
    cia_max NUMERIC(5,2) NOT NULL DEFAULT 40.00,
    see_max NUMERIC(5,2) NOT NULL DEFAULT 60.00,
    cia_weight NUMERIC(5,2) NOT NULL DEFAULT 40.00,
    see_weight NUMERIC(5,2) NOT NULL DEFAULT 60.00,
    min_see_marks NUMERIC(5,2)
);

CREATE TABLE faculty_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    faculty_id BIGINT NOT NULL REFERENCES faculty(id) ON DELETE CASCADE,
    course_id BIGINT NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    academic_year VARCHAR(50),
    UNIQUE(faculty_id, course_id, academic_year)
);

CREATE TABLE examinations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    academic_year VARCHAR(50) NOT NULL,
    semester INTEGER NOT NULL,
    regulation_id BIGINT REFERENCES regulations(id) ON DELETE RESTRICT,
    status VARCHAR(50) NOT NULL DEFAULT 'DRAFT',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE exam_courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id BIGINT NOT NULL REFERENCES examinations(id) ON DELETE CASCADE,
    course_id BIGINT NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    cia_deadline TIMESTAMP,
    see_deadline TIMESTAMP,
    internal_locked BOOLEAN DEFAULT FALSE,
    internal_published_at TIMESTAMP,
    UNIQUE(exam_id, course_id)
);

CREATE TABLE course_registrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    course_id BIGINT NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    exam_id BIGINT NOT NULL REFERENCES examinations(id) ON DELETE CASCADE,
    status VARCHAR(50) NOT NULL DEFAULT 'REGISTERED',
    verified_by VARCHAR(255),
    UNIQUE(student_id, course_id, exam_id)
);

CREATE TABLE dummy_mappings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id BIGINT NOT NULL REFERENCES examinations(id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    course_id BIGINT NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    dummy_id VARCHAR(50) NOT NULL,
    UNIQUE(exam_id, course_id, dummy_id),
    UNIQUE(exam_id, course_id, student_id)
);

CREATE TABLE marks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_course_id BIGINT NOT NULL REFERENCES exam_courses(id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    cia_marks NUMERIC(5,2),
    see_marks NUMERIC(5,2),
    moderated_marks NUMERIC(5,2),
    flag VARCHAR(50) NOT NULL DEFAULT 'NONE',
    status VARCHAR(50) NOT NULL DEFAULT 'DRAFT',
    entered_by VARCHAR(255),
    verified_with_students BOOLEAN DEFAULT FALSE,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(exam_course_id, student_id)
);

CREATE TABLE mark_alterations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    marks_id BIGINT NOT NULL REFERENCES marks(id) ON DELETE CASCADE,
    old_value NUMERIC(5,2),
    new_value NUMERIC(5,2),
    reason TEXT NOT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'PENDING',
    requested_by VARCHAR(255) NOT NULL,
    signed_by VARCHAR(255),
    comments TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    reviewed_at TIMESTAMP
);

CREATE TABLE results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id BIGINT NOT NULL REFERENCES examinations(id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    course_id BIGINT NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    cia_marks NUMERIC(5,2),
    see_marks NUMERIC(5,2),
    total NUMERIC(5,2),
    grade VARCHAR(10),
    grade_point INTEGER,
    status VARCHAR(50) NOT NULL,
    explanation TEXT,
    UNIQUE(exam_id, student_id, course_id)
);

CREATE TABLE semester_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id BIGINT NOT NULL REFERENCES examinations(id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    gpa NUMERIC(4,2),
    cgpa NUMERIC(4,2),
    total_credits NUMERIC(5,1),
    earned_credits NUMERIC(5,1),
    arrear_count INTEGER DEFAULT 0,
    rank_position INTEGER,
    workflow_status VARCHAR(50) NOT NULL DEFAULT 'DRAFT',
    result_reference VARCHAR(100) NOT NULL UNIQUE,
    published_at TIMESTAMP,
    UNIQUE(exam_id, student_id)
);

CREATE TABLE rpb_meetings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id BIGINT NOT NULL REFERENCES examinations(id) ON DELETE CASCADE,
    meeting_date TIMESTAMP NOT NULL,
    members TEXT NOT NULL,
    university_nominee VARCHAR(255),
    minutes_ref VARCHAR(255) NOT NULL,
    sign_off_by VARCHAR(255),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE malpractice_cases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id BIGINT NOT NULL REFERENCES examinations(id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    course_id BIGINT NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    flagged_by VARCHAR(255) NOT NULL,
    reason TEXT NOT NULL,
    decision VARCHAR(50) NOT NULL DEFAULT 'PENDING',
    decided_by VARCHAR(255),
    penalty_notes TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMP,
    UNIQUE(exam_id, student_id, course_id)
);

CREATE TABLE revaluation_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    course_id BIGINT NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    exam_id BIGINT NOT NULL REFERENCES examinations(id) ON DELETE CASCADE,
    reason TEXT,
    fee_paid_flag BOOLEAN DEFAULT FALSE,
    photocopy_requested BOOLEAN DEFAULT FALSE,
    photocopy_available_at TIMESTAMP,
    photocopy_received_at TIMESTAMP,
    status VARCHAR(50) NOT NULL DEFAULT 'REQUESTED',
    old_marks NUMERIC(5,2),
    new_marks NUMERIC(5,2),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMP
);

CREATE TABLE grade_scales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    regulation_id BIGINT NOT NULL REFERENCES regulations(id) ON DELETE CASCADE,
    grade VARCHAR(10) NOT NULL,
    min_marks NUMERIC(5,2) NOT NULL,
    max_marks NUMERIC(5,2) NOT NULL,
    grade_point INTEGER NOT NULL,
    UNIQUE(regulation_id, grade)
);

CREATE TABLE grading_configs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    regulation_id BIGINT NOT NULL UNIQUE REFERENCES regulations(id) ON DELETE CASCADE,
    pass_rules VARCHAR(255) DEFAULT 'NO_U_AND_NO_AB',
    min_see_marks_enabled BOOLEAN DEFAULT FALSE,
    default_min_see_marks NUMERIC(5,2) DEFAULT 27.00,
    rank_requires_no_arrear BOOLEAN DEFAULT TRUE,
    reval_window_days INTEGER DEFAULT 15,
    reval_window_start_event VARCHAR(100) DEFAULT 'RESULT_PUBLICATION',
    publish_sla_days INTEGER DEFAULT 3
);

CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timestamp TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    user_id VARCHAR(255),
    role VARCHAR(50),
    ip_address VARCHAR(100),
    action VARCHAR(100) NOT NULL,
    entity VARCHAR(100) NOT NULL,
    entity_id VARCHAR(100),
    old_value TEXT,
    new_value TEXT,
    prev_hash VARCHAR(255),
    hash VARCHAR(255) NOT NULL
);

-- Indexes for performance and quick lookups
CREATE INDEX idx_students_reg_no ON students(register_no);
CREATE INDEX idx_students_dept ON students(department_id);
CREATE INDEX idx_courses_code ON courses(code);
CREATE INDEX idx_exam_courses_exam ON exam_courses(exam_id);
CREATE INDEX idx_course_reg_student ON course_registrations(student_id);
CREATE INDEX idx_course_reg_exam ON course_registrations(exam_id);
CREATE INDEX idx_marks_exam_course ON marks(exam_course_id);
CREATE INDEX idx_marks_student ON marks(student_id);
CREATE INDEX idx_results_exam_student ON results(exam_id, student_id);
CREATE INDEX idx_sem_results_ref ON semester_results(result_reference);
CREATE INDEX idx_audit_timestamp ON audit_logs(timestamp);
CREATE INDEX idx_audit_entity ON audit_logs(entity, entity_id);
